"""Stage port consumed by graph nodes; no framework or infrastructure dependency."""
from typing import Any, Protocol
from pathlib import Path
from math_agent.contracts import Source, Candidate, Review

class ClassicStages(Protocol):
    directory: Path
    settings: Any
    def audit(self, kind: str, detail: dict) -> None: ...
    def extract(self, feedback=None) -> Source: ...
    def solve(self, source: Source, feedback=None, previous=None, stage="solve", *, allowed_tabs=None) -> Candidate: ...
    def repair_math(self, source: Source, previous: Candidate, feedback: list) -> Candidate: ...
    def observe(self, candidate: Candidate) -> dict: ...
    def review(self, source: Source, candidate: Candidate, observation: dict) -> Review: ...
